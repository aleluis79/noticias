using System.Net;
using NewsAggregator.Services;
using NewsAggregator.Services.Archive;
using NewsAggregator.Services.Grouping;
using NewsAggregator.Services.Summaries;
using NewsAggregator.Services.Tts;
using NewsAggregator.Models;
using Microsoft.Extensions.Options;
using Microsoft.OpenApi.Models;
using Microsoft.Playwright;

var builder = WebApplication.CreateBuilder(args);

// Playwright is only used as a fallback for sources that render their news with
// JavaScript, so the browser is launched lazily on first use.
IPlaywright playwright = await Playwright.CreateAsync();

// Register IPlaywright as a singleton
builder.Services.AddSingleton<IPlaywright>(playwright);

// Shared HTTP client used for the fast path (plain HTML requests).
builder.Services.AddSingleton(_ =>
{
    var handler = new SocketsHttpHandler
    {
        AutomaticDecompression = DecompressionMethods.All,
        PooledConnectionLifetime = TimeSpan.FromMinutes(5),
        MaxConnectionsPerServer = 4
    };

    var client = new HttpClient(handler) { Timeout = TimeSpan.FromSeconds(20) };
    client.DefaultRequestHeaders.UserAgent.ParseAdd(NewsAggregationService.UserAgent);
    client.DefaultRequestHeaders.Accept.ParseAdd("text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8");
    client.DefaultRequestHeaders.AcceptLanguage.ParseAdd("es-AR,es;q=0.9,en;q=0.8");
    return client;
});

// Register NewsAggregationService once and expose it through its interface
builder.Services.AddSingleton(TimeProvider.System);
builder.Services.AddOptions<ArchiveOptions>()
    .Bind(builder.Configuration.GetSection(ArchiveOptions.SectionName))
    .PostConfigure(options => options.ResolvePaths(builder.Environment.ContentRootPath));
builder.Services.AddSingleton<IDailyEditionStore, DailyEditionStore>();
builder.Services.AddSingleton<EditionClock>();
builder.Services.AddSingleton<IEditionHistoryService, EditionHistoryService>();
builder.Services.AddSingleton<NewsAggregationService>();
builder.Services.AddSingleton<INewsAggregationService>(sp => sp.GetRequiredService<NewsAggregationService>());
builder.Services.AddSingleton<ArticleContentService>();
builder.Services.AddSingleton<IArticleContentService>(sp => sp.GetRequiredService<ArticleContentService>());
builder.Services.AddSingleton<IStoryGroupingService, StoryGroupingService>();

// Local Piper speech synthesis. Paths are resolved against the API content root
// so `dotnet run` can use api/.tts without absolute configuration.
builder.Services.AddOptions<TtsOptions>()
    .Bind(builder.Configuration.GetSection("Tts"))
    .PostConfigure(options => options.ResolvePaths(builder.Environment.ContentRootPath));
builder.Services.AddSingleton<IProcessRunner, ProcessRunner>();
builder.Services.AddSingleton<ITextToSpeechService, PiperTtsService>();

// On-demand article summaries generated by a local Ollama model. The service is
// a singleton so concurrent requests share one generation and one concurrency
// gate; the named HTTP client has a generous global timeout, while each request
// also enforces its own configured timeout.
builder.Services.AddOptions<SummaryOptions>()
    .Bind(builder.Configuration.GetSection(SummaryOptions.SectionName))
    .PostConfigure(options => options.ResolvePaths(builder.Environment.ContentRootPath));
builder.Services.AddHttpClient("summaries", client =>
{
    client.Timeout = TimeSpan.FromMinutes(10);
});
builder.Services.AddSingleton<IArticleSummaryService>(serviceProvider =>
{
    var client = serviceProvider
        .GetRequiredService<IHttpClientFactory>()
        .CreateClient("summaries");

    return new ArticleSummaryService(
        serviceProvider.GetRequiredService<IOptions<SummaryOptions>>(),
        serviceProvider.GetRequiredService<IArticleContentService>(),
        client,
        serviceProvider.GetRequiredService<ILogger<ArticleSummaryService>>());
});

builder.Services.AddEndpointsApiExplorer();
builder.Services.AddSwaggerGen(options =>
{
    options.SwaggerDoc("v1", new OpenApiInfo { Title = "News Aggregator API", Version = "v1" });
});
builder.Services.AddControllers();
builder.Services.AddCors(options =>
{
    options.AddPolicy("ReactFrontend",
        policy => policy.WithOrigins(
                            "http://localhost:5173", // Default Vite port
                            "http://127.0.0.1:5173")
                        .AllowAnyHeader()
                        .AllowAnyMethod());
});

var app = builder.Build();

// The HTTP client and the browser (when needed) are resolved lazily by the service.
var newsService = app.Services.GetRequiredService<NewsAggregationService>();
app.Lifetime.ApplicationStopping.Register(newsService.Dispose);

// Configure the HTTP request pipeline.
if (app.Environment.IsDevelopment())
{
    app.UseSwagger();
    app.UseSwaggerUI();
}

app.UseHttpsRedirection();
app.UseCors("ReactFrontend"); // Apply CORS policy
app.UseAuthorization();
app.MapControllers();

var summaries = new[]
{
    "Freezing", "Bracing", "Chilly", "Cool", "Mild", "Warm", "Balmy", "Hot", "Sweltering", "Scorching"
};

app.MapGet("/weatherforecast", () =>
{
    var forecast = Enumerable.Range(1, 5).Select(index =>
        new WeatherForecast
        (
            DateOnly.FromDateTime(DateTime.Now.AddDays(index)),
            Random.Shared.Next(-20, 55),
            summaries[Random.Shared.Next(summaries.Length)]
        ))
        .ToArray();
    return forecast;
})
.WithName("GetWeatherForecast");

app.Run();

record WeatherForecast(DateOnly Date, int TemperatureC, string? Summary)
{
    public int TemperatureF => 32 + (int)(TemperatureC / 0.5556);
}
